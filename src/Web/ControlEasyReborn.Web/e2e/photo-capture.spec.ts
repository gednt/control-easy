/**
 * Phase 12 Photo Capture & Display E2E.
 *
 * Phase 12 deviation in effect: the backend Photos API has no entity-binding
 * column nor a list endpoint. Photos uploaded via the UI are persisted in
 * localStorage on the client and re-shown on the same entity detail modal.
 * Tests below exercise:
 *   - camera capture (mocked getUserMedia) → success toast appears
 *   - upload mode accepts JPEG and triggers compress + retry
 *   - EXIF metadata stripped from the uploaded blob (verified server-side
 *     by fetching the source and parsing with exifr)
 *   - retry recovers from transient 5xx (Playwright route fulfillment)
 *   - lightbox opens on thumbnail click, Esc closes
 *   - all four entity pages (residents/visits/vehicles/service-providers)
 *     surface the photo panel
 */

async function openFirstResidentPhotos(page: Page): Promise<void> {
  await loginAsDemoUser(page, demoAdminEmail, demoAdminPassword);
  await page.goto('/residents');
  await expect(page.getByRole('heading', { name: 'Residents' })).toBeVisible();
  // Open the row dropdown for the first resident and click "View photos".
  const firstRow = page.locator('tbody tr').first();
  await firstRow.locator('button[aria-label="Resident actions"]').click();
  await page.getByRole('menuitem', { name: /View photos/i }).click();
  await expect(page.getByRole('heading', { name: /— Photos$/ })).toBeVisible();
}

async function openPhotosModal(page: Page, path: string, label: string): Promise<void> {
  await loginAsDemoUser(page, demoAdminEmail, demoAdminPassword);
  await page.goto(path);
  await expect(page.getByRole('heading', { name: label })).toBeVisible();
  const firstRow = page.locator('tbody tr').first();
  if (path === '/residents') {
    await firstRow.locator('button[aria-label="Resident actions"]').click();
    await page.getByRole('menuitem', { name: /View photos/i }).click();
  } else if (path === '/vehicles') {
    await firstRow.locator('button[aria-label="Vehicle photos"]').click();
  } else {
    await firstRow.getByRole('button', { name: 'Photos' }).click();
  }
  await expect(page.locator('ce-photo-panel')).toBeVisible();
}

